#!/usr/bin/env python3
"""Replay real demonstrations in the CAD sim, seen through the fitted real cameras.

Each real frame records both arms' joint angles. This poses the CAD arms of
sim/bimanual_cad.py exactly so and renders them from the cameras fitted to the
demonstrations (sim/real_cameras.json: the overhead webcam solved from clicked
fingertips, with its lens distortion; the wrist fisheyes fitted to arm outlines),
next to the real frames. It also splits each demonstration into phases from the
grippers' openings: each part has its own width, so how far a gripper closes
tells which part it holds.

- right arm: opens, then closes on the large carrier (about 1.0 rad) and holds it;
- left arm: closes on the gear (about 0.6), releases it onto the carrier, closes
  empty to push it home (about 0), opens, closes on the pin (about 0.15),
  releases it, and closes empty again to press it.

This is the first step toward real-to-sim data: replayed real motions rendered
with any look, then (later) part poses recovered from these phases and new
demonstrations generated by moving the parts and transforming each phase.

    python tools/replay_real_in_sim.py --episodes 12 60 --output outputs/replay
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
if sys.platform.startswith('linux'):
    os.environ.setdefault('MUJOCO_GL', 'egl')
import cv2
import mujoco
import numpy as np

from sim.bimanual import OVERHEAD_CROP, _look_at
from tools.fit_cameras import SIZE, WRIST_LIMIT, WRIST_RENDER, WRIST_RENDER_FOV, Scene, scene_table_z
from scipy.spatial.transform import Rotation

CAMERAS = ('overhead', 'wrist_port2', 'wrist_port3')
# Gripper openings (rad, 0 closed .. 2 open) that mean "holding this part".
HOLD = {'carrier': (.75, 1.35), 'gear': (.35, .85), 'pin': (.06, .35)}
EMPTY_CLOSED = .06


# ---------------------------------------------------------------- phases ----

def runs(mask):
    """[(start, stop)] of consecutive True frames."""
    edges = np.flatnonzero(np.diff(np.r_[0, mask.astype(int), 0]))
    return list(zip(edges[::2], edges[1::2]))


def phases(states, fps=20, min_hold=.4):
    """Per-arm phase segments from the gripper openings.

    A hold is a stretch of at least `min_hold` seconds where the opening sits
    still inside a part's band. The left arm's holds are named in task order
    (gear first, then pin) by their band.
    """
    smooth = lambda x: np.convolve(x, np.ones(5) / 5, mode='same')
    out = {}
    for side, col in (('left', 6), ('right', 13)):
        opening = smooth(states[:, col])
        steady = np.abs(np.gradient(opening)) < .03
        segments = []
        for part, (lo, hi) in HOLD.items():
            if (side == 'right') != (part == 'carrier'):
                continue
            for a, b in runs((opening > lo) & (opening < hi) & steady):
                if b - a >= min_hold * fps:
                    segments.append(dict(phase=f'{part}_held', start=int(a), stop=int(b)))
        if side == 'left':
            for a, b in runs((opening < EMPTY_CLOSED) & steady):
                if b - a >= min_hold * fps:
                    segments.append(dict(phase='closed_empty', start=int(a), stop=int(b)))
        segments.sort(key=lambda s: s['start'])
        out[side] = segments
    return out


def phase_labels(segments, count):
    labels = ['moving'] * count
    for s in segments:
        for i in range(s['start'], s['stop']):
            labels[i] = s['phase']
    return labels


# ---------------------------------------------------------------- render ----

class RealViews:
    """RGB renders of the posed CAD scene through the fitted real cameras (256 x 256)."""

    def __init__(self, scene: Scene):
        self.scene = scene
        m = scene.model
        cameras = json.loads((ROOT / 'sim/real_cameras.json').read_text())
        self.params = {c: np.array(list(cameras[c]['params'].values()), float) for c in CAMERAS}
        self.overhead = mujoco.Renderer(m, 480, 640)
        self.wrist = mujoco.Renderer(m, WRIST_RENDER, WRIST_RENDER)
        self.maps = {c: self._maps(c) for c in CAMERAS}
        self.options = mujoco.MjvOption()
        self.options.sitegroup[:] = 0  # hide debug markers (grip_site and the like)

    def _maps(self, camera):
        p = self.params[camera]
        if camera == 'overhead':
            fovy, cx, cy, k1 = p[6:10]
            x0, y0, x1, y1 = OVERHEAD_CROP
            v, u = np.mgrid[y0:y1, x0:x1].astype(np.float32)
            f = 240 / np.tan(np.radians(fovy / 2))
            xn, yn = (u - 319.5 - cx) / f, (v - 239.5 - cy) / f
            scale = 1 + k1 * (xn ** 2 + yn ** 2)
            fr = 240 / np.tan(np.radians(min(fovy + 12, 100) / 2))
            return (319.5 + xn * scale * fr).astype(np.float32), (239.5 + yn * scale * fr).astype(np.float32), None
        f, cx, cy = p[6:9]
        v, u = np.mgrid[0:SIZE, 0:SIZE].astype(np.float32)
        du, dv = u - cx, v - cy
        radius = np.hypot(du, dv)
        theta = np.minimum(radius / f, np.radians(89))
        fs = (WRIST_RENDER / 2) / np.tan(np.radians(WRIST_RENDER_FOV / 2))
        scale = np.where(radius > 0, fs * np.tan(theta) / np.maximum(radius, 1e-6), 0)
        return ((du * scale + (WRIST_RENDER - 1) / 2).astype(np.float32),
                (dv * scale + (WRIST_RENDER - 1) / 2).astype(np.float32), theta <= WRIST_LIMIT)

    def place_cameras(self):
        """Put every scene camera where its fit says (the right base follows the overhead solve)."""
        s, m = self.scene, self.scene.model
        px, py, pz, tx, ty, roll, fovy = self.params['overhead'][:7]
        lift = np.array([0, 0, scene_table_z()])
        cam = s.cam['overhead']
        m.cam_pos[cam] = np.add([px, py, pz], lift)
        m.cam_quat[cam] = _look_at(np.add([px, py, pz], lift), np.add([tx, ty, 0.], lift), roll)
        m.cam_fovy[cam] = min(fovy + 12, 100)
        s.set_right_base(*self.params['overhead'][10:13])
        for camera in ('wrist_port2', 'wrist_port3'):
            dx, dy, dz, rx, ry, rz = self.params[camera][:6]
            cam = s.cam[camera]
            m.cam_pos[cam] = s.wrist_pos[camera] + [dx, dy, dz]
            w, x, y, z = s.wrist_quat[camera]
            q = (Rotation.from_quat([x, y, z, w]) * Rotation.from_rotvec([rx, ry, rz], degrees=True)).as_quat()
            m.cam_quat[cam] = [q[3], q[0], q[1], q[2]]
            m.cam_fovy[cam] = WRIST_RENDER_FOV

    def render(self, state):
        self.scene.pose(state)
        out = {}
        for camera in CAMERAS:
            renderer = self.overhead if camera == 'overhead' else self.wrist
            renderer.update_scene(self.scene.data, self.scene.cam[camera], self.options)
            map_x, map_y, inside = self.maps[camera]
            image = cv2.remap(renderer.render(), map_x, map_y, cv2.INTER_LINEAR, borderValue=0)
            if inside is not None:
                image[~inside] = 0
            out[camera] = image
        return out


# ---------------------------------------------------------------- main ------

def main():
    from tools.augment_real_dataset import decode, episode_rows
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--root', type=Path, default=ROOT / 'outputs/real_gear', help='local copy of the real dataset')
    parser.add_argument('--episodes', type=int, nargs='+', default=[12])
    parser.add_argument('--output', type=Path, default=ROOT / 'outputs/replay')
    parser.add_argument('--stills', type=int, default=4, help='frames per episode in the contact sheet')
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    scene = Scene()
    views = RealViews(scene)
    views.place_cameras()
    report = {}
    for episode in args.episodes:
        numeric, images = episode_rows(args.root, episode)
        states = numeric['observation.state'].astype(np.float64)
        segments = phases(states)
        labels = {side: phase_labels(segments[side], len(states)) for side in segments}
        report[episode] = segments
        print(f'demo {episode} ({len(states)} frames, {len(states) / 20:.1f} s):')
        for side, segs in segments.items():
            print(f'  {side:5s} ' + ', '.join(f"{s['phase']} {s['start'] / 20:.1f}-{s['stop'] / 20:.1f}s" for s in segs))
        real = {c: decode(images[c]) for c in CAMERAS}
        video = cv2.VideoWriter(str(args.output / f'demo_{episode:03d}.mp4'), cv2.VideoWriter_fourcc(*'mp4v'), 20,
                                (SIZE * 3, SIZE * 3))
        stills = set(np.linspace(0, len(states) - 1, args.stills + 2)[1:-1].astype(int).tolist())
        sheet = []
        for i, state in enumerate(states):
            sim = views.render(state)
            rows = []
            for camera in CAMERAS:
                blend = cv2.addWeighted(real[camera][i], .5, sim[camera], .5, 0)
                rows.append(np.concatenate([real[camera][i], sim[camera], blend], 1))
            frame = np.concatenate(rows, 0)
            text = f"{i / 20:5.1f}s  left: {labels['left'][i]}  right: {labels['right'][i]}"
            cv2.putText(frame, text, (6, 16), cv2.FONT_HERSHEY_SIMPLEX, .45, (255, 255, 255), 1, cv2.LINE_AA)
            video.write(cv2.cvtColor(frame, cv2.COLOR_RGB2BGR))
            if i in stills:
                sheet.append(frame)
        video.release()
        cv2.imwrite(str(args.output / f'demo_{episode:03d}.jpg'),
                    cv2.cvtColor(np.concatenate(sheet, 1), cv2.COLOR_RGB2BGR), [cv2.IMWRITE_JPEG_QUALITY, 88])
        print(f'  wrote {args.output}/demo_{episode:03d}.mp4 and .jpg (columns per camera: real | sim | blend)')
    (args.output / 'phases.json').write_text(json.dumps(report, indent=2) + '\n')


if __name__ == '__main__':
    main()
